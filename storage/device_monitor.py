import os
import threading
import time

from watchdog.events import FileSystemEventHandler
from watchdog.observers import Observer

from config import LOCAL_SECONDARY_PATH, LOCAL_SSD_PATH
from database import (
    get_block_by_filename,
    get_block_by_filename_and_tier,
    mark_block_deleted,
    register_file_if_needed,
    update_filename,
)
from engine.migration_engine import (
    get_tier_for_path,
    is_internal_migration,
)
from engine.storage_controller import process_access


class StorageEventHandler(FileSystemEventHandler):
    def __init__(self, callback):
        super().__init__()
        self.callback = callback
        self.last_event_time = {}
        self.debounce_seconds = 1.5

    def should_process(self, file_path):
        current_time = time.time()
        last_time = self.last_event_time.get(file_path, 0)
        if current_time - last_time < self.debounce_seconds:
            return False
        self.last_event_time[file_path] = current_time
        return True

    def on_created(self, event):
        if not event.is_directory and self.should_process(event.src_path):
            self.callback("CREATED", event.src_path)

    def on_modified(self, event):
        if not event.is_directory and self.should_process(event.src_path):
            self.callback("MODIFIED", event.src_path)

    def on_deleted(self, event):
        if not event.is_directory and self.should_process(event.src_path):
            self.callback("DELETED", event.src_path)

    def on_moved(self, event):
        if not event.is_directory and self.should_process(event.dest_path):
            self.callback("MOVED", event.dest_path, event.src_path)


class DeviceMonitor:
    def __init__(self, drive_path, callback):
        self.drive_path = drive_path
        self.callback = callback
        self.observer = None
        self.running = False

    def start(self):
        if self.running:
            return True
        if not os.path.exists(self.drive_path):
            print(f"Drive/folder not found: {self.drive_path}")
            return False

        event_handler = StorageEventHandler(self.callback)
        self.observer = Observer()
        self.observer.schedule(event_handler, self.drive_path, recursive=True)
        self.observer.start()
        self.running = True
        print(f"Live monitoring started: {self.drive_path}")
        return True

    def stop(self):
        if self.observer and self.running:
            self.observer.stop()
            self.observer.join(timeout=3)
            self.running = False
            print(f"Live monitoring stopped: {self.drive_path}")

    def is_available(self):
        return os.path.exists(self.drive_path)

    def is_healthy(self):
        return bool(
            self.running
            and self.observer is not None
            and self.observer.is_alive()
            and os.path.exists(self.drive_path)
        )


def _print_event_header(event_type, filename, file_path, tier):
    print()
    print("========================================")
    print("LIVE STORAGE EVENT")
    print("========================================")
    print(f"Event    : {event_type}")
    print(f"File     : {filename}")
    print(f"Tier     : {tier or 'UNKNOWN'}")
    print(f"Path     : {file_path}")


def handle_storage_event(event_type, file_path, old_path=None):
    filename = os.path.basename(file_path)
    tier = get_tier_for_path(file_path)

    # Events generated by the migration engine must never be treated as
    # user activity, regardless of whether they are CREATE/DELETE/MODIFY.
    if is_internal_migration(file_path) or (
        old_path and is_internal_migration(old_path)
    ):
        _print_event_header(event_type, filename, file_path, tier)
        print("Activity : INTERNAL MIGRATION")
        print("Status   : Migration-generated filesystem event ignored.")
        print("========================================")
        return

    _print_event_header(event_type, filename, file_path, tier)

    if event_type == "CREATED":
        if tier is None:
            print("Status   : File is outside managed storage tiers.")
            print("========================================")
            return

        success, block_id, message = register_file_if_needed(file_path, tier)
        print(f"Status   : {message if success else 'Registration failed: ' + message}")
        if success:
            print(f"Block ID : {block_id}")
            print(f"Tier     : {tier}")
        print("========================================")
        return

    if event_type == "MOVED":
        # Many editors save atomically: write a temporary file, then rename it
        # over the original. Watchdog reports MOVED rather than MODIFIED.
        destination_block = (
            get_block_by_filename_and_tier(filename, tier)
            if tier else get_block_by_filename(filename)
        )
        if destination_block is not None and os.path.isfile(file_path):
            block_id = destination_block[0]
            success, result = process_access(block_id, "WRITE")
            print(f"Block ID : {block_id}")
            print("Activity : WRITE (atomic save / replacement)")
            if success:
                print(f"Temperature: {result['temperature']}")
                print(f"Status   : {result['label']}")
                print(f"Current  : {result['current_tier']}")
                print(f"Target   : {result['recommended_tier']}")
                print(f"Migration: {result['migration']}")
            else:
                print(f"Engine error: {result['message']}")
            print("========================================")
            return

        old_filename = os.path.basename(old_path) if old_path else ""
        old_tier = get_tier_for_path(old_path) if old_path else None
        block = (
            get_block_by_filename_and_tier(old_filename, old_tier)
            if old_tier else get_block_by_filename(old_filename)
        )
        if block is not None:
            block_id = block[0]
            success, message = update_filename(block_id, filename)
            if success:
                print(f"Rename   : {old_filename} -> {filename}")
                print(f"Block ID : {block_id}")
                print("Status   : Database filename updated.")
                # Renaming an existing managed file is also a write-like event.
                process_access(block_id, "WRITE")
            else:
                print(f"Rename failed: {message}")
        else:
            # If an application created a temp file and then moved it into the
            # managed folder, register the final physical file.
            if tier and os.path.isfile(file_path):
                success, block_id, message = register_file_if_needed(file_path, tier)
                print(f"Status   : {message if success else 'Registration failed: ' + message}")
                if success:
                    process_access(block_id, "WRITE")
            else:
                print("Status   : Original file was not registered.")
        print("========================================")
        return

    if event_type == "MODIFIED":
        block = (
            get_block_by_filename_and_tier(filename, tier)
            if tier else get_block_by_filename(filename)
        )
        if block is None and tier and os.path.isfile(file_path):
            registered, new_block_id, registration_message = register_file_if_needed(file_path, tier)
            if registered:
                print(f"Status   : {registration_message}")
                block = get_block_by_filename_and_tier(filename, tier)

        if block is None:
            print("Status   : File is not registered in this managed tier.")
            print("Hint     : Check the configured SSD/HDD root paths.")
            print("========================================")
            return

        block_id = block[0]
        success, result = process_access(block_id, "WRITE")
        if success:
            print(f"Block ID : {block_id}")
            print(f"Activity : WRITE")
            print(f"Temperature: {result['temperature']}")
            print(f"Status   : {result['label']}")
            print(f"Current  : {result['current_tier']}")
            print(f"Target   : {result['recommended_tier']}")
            print(f"Migration: {result['migration']}")
        else:
            print(f"Engine error: {result['message']}")
        print("========================================")
        return

    if event_type == "DELETED":
        block = (
            get_block_by_filename_and_tier(filename, tier)
            if tier else get_block_by_filename(filename)
        )
        if block is not None:
            mark_block_deleted(block[0])
            print(f"Block ID : {block[0]}")
        print("Activity : FILE DELETED")
        print("Status   : Block marked DELETED; history retained.")
        print("========================================")
        return

    print("Status   : Unknown event.")
    print("========================================")


def start_monitor(drive_path, callback):
    monitor = DeviceMonitor(drive_path, callback)
    monitor_thread = threading.Thread(target=monitor.start, daemon=True)
    monitor_thread.start()
    return monitor


if __name__ == "__main__":
    print("\n========================================")
    print("HYBRID STORAGE LIVE MONITOR")
    print("========================================")
    monitors = [
        start_monitor(LOCAL_SSD_PATH, handle_storage_event),
        start_monitor(LOCAL_SECONDARY_PATH, handle_storage_event),
    ]
    print(f"Monitoring SSD      : {LOCAL_SSD_PATH}")
    print(f"Monitoring SECONDARY: {LOCAL_SECONDARY_PATH}")
    print("Press Ctrl + C to stop.\n")
    try:
        while True:
            time.sleep(1)
    except KeyboardInterrupt:
        for monitor in monitors:
            monitor.stop()
